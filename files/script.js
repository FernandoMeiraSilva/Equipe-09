function desenharLinha({ camada, valores, maximo, centrado }) {
  camada.replaceChildren();
  const { clientWidth: largura, clientHeight: altura } = camada;
  if (!largura) return;

  const total = valores.length;
  const pontos = valores.map((valor, indice) => ({
    x: centrado ? ((indice + 0.5) / total) * largura : (indice / (total - 1)) * largura,
    y: altura - (valor / maximo) * altura
  }));

  pontos.forEach((ponto, indice) => {
    if (indice > 0) {
      const anterior = pontos[indice - 1];
      const dx = ponto.x - anterior.x;
      const dy = ponto.y - anterior.y;
      Object.assign(criar("segmento", "", camada).style, {
        left: `${anterior.x}px`,
        top: `${anterior.y - 1}px`,
        width: `${Math.hypot(dx, dy)}px`,
        transform: `rotate(${Math.atan2(dy, dx)}rad)`
      });
    }
    Object.assign(criar("marcador", "", camada).style, { left: `${ponto.x}px`, top: `${ponto.y}px` });
  });
}

const desenharLinhas = () => linhas.forEach(desenharLinha);

function criarQuadro(pai, { maxEsq, divisoes, tituloEsq, maxDir, tituloDir, rotulosX, tituloX, distribuicao = "centrado" }) {
  const quadro = criar(`quadro${maxDir ? "" : " simples"}`, "", pai);
  criar("titulo-eixo esq", tituloEsq, quadro);
  const eixoEsq = criar("eixo esq", "", quadro);
  const plot = criar("plot", "", quadro);
  const eixoDir = maxDir ? criar("eixo dir", "", quadro) : null;
  if (maxDir) criar("titulo-eixo dir", tituloDir, quadro);

  for (let i = 0; i <= divisoes; i++) {
    const topo = `${(i / divisoes) * 100}%`;
    criar("plot-grade", "", plot).style.top = topo;
    criar("eixo-rotulo", formatar(maxEsq - (maxEsq / divisoes) * i), eixoEsq).style.top = topo;
    if (eixoDir) criar("eixo-rotulo", formatar(maxDir - (maxDir / divisoes) * i), eixoDir).style.top = topo;
  }

  const eixoX = criar(`rotulos-x ${distribuicao}`, "", quadro);
  rotulosX.forEach((rotulo) => criar("rotulo-x", rotulo, eixoX));
  if (tituloX) criar("titulo-x", tituloX, quadro);
  return plot;
}

function desenharGrupos(corpo, { categorias, series, max, divisoes, titulo, destaque }) {
  legenda(corpo, series.map((serie, indice) => ({ nome: serie.nome, classe: `serie-${indice}` })));
  const plot = criarQuadro(corpo, { maxEsq: max, divisoes, tituloEsq: titulo, rotulosX: categorias });
  const colunas = criar("colunas", "", plot);

  categorias.forEach((_, indice) => {
    const coluna = criar(`coluna${indice === destaque ? " atipico" : ""}`, "", colunas);
    const grupo = criar("grupo", "", coluna);
    series.forEach((serie, posicao) => {
      const barra = criar(`barra-serie serie-${posicao}`, "", grupo);
      barra.title = `${serie.nome} · ${categorias[indice]}: ${pct(serie.valores[indice])}`;
      barra.style.height = `${(serie.valores[indice] / max) * 100}%`;
    });
  });
}

function desenharDispersao(corpo, { pontos, xMin, xMax, yMax, tituloY, tituloX, rotulosX, denso }) {
  const plot = criarQuadro(corpo, { maxEsq: yMax, divisoes: 4, tituloEsq: tituloY, rotulosX, tituloX, distribuicao: "bordas" });
  pontos.forEach((ponto) => {
    const elemento = criar(`ponto-dado${denso ? " denso" : ""}${ponto.classe ? ` ${ponto.classe}` : ""}`, "", plot);
    elemento.title = ponto.nome;
    Object.assign(elemento.style, {
      left: `${((ponto.x - xMin) / (xMax - xMin)) * 100}%`,
      bottom: `${(ponto.y / yMax) * 100}%`
    });
  });
}

function desenharBarras(corpo, { itens, max, divisoes, largura }) {
  corpo.style.setProperty("--rotulo", `${largura}px`);
  const lista = criar("barras-h", "", corpo);
  const eixo = criar("barras-eixo", "", corpo);
  const grade = criar("barras-grade", "", lista);

  for (let i = 0; i <= divisoes; i++) {
    const posicao = `${(i / divisoes) * 100}%`;
    criar("barras-grade-linha", "", grade).style.left = posicao;
    criar("barras-eixo-rotulo", formatar((max / divisoes) * i), eixo).style.left = posicao;
  }

  itens.forEach((item) => {
    const linha = criar("linha-h", "", lista);
    const nome = criar("linha-nome", item.nome, linha);
    if (item.titulo) nome.title = item.titulo;
    const trilho = criar("linha-trilho", "", linha);
    const percentual = (item.valor / max) * 100;
    criar(`linha-barra ${item.classe}`, "", trilho).style.width = `${percentual}%`;
    criar("linha-valor", item.texto, trilho).style.left = `calc(${percentual}% + 4px)`;
  });
}

