function criar(classe, texto, pai) {
  const elemento = document.createElement("div");
  if (classe) elemento.className = classe;
  if (texto !== undefined && texto !== "") elemento.textContent = texto;
  if (pai) pai.appendChild(elemento);
  return elemento;
}

