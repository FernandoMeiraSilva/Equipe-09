function correlacao(x, y) {
  const mediaX = soma(x) / x.length;
  const mediaY = soma(y) / y.length;
  let covariancia = 0;
  let varianciaX = 0;
  let varianciaY = 0;
  x.forEach((valor, indice) => {
    const dx = valor - mediaX;
    const dy = y[indice] - mediaY;
    covariancia += dx * dy;
    varianciaX += dx * dx;
    varianciaY += dy * dy;
  });
  return covariancia / Math.sqrt(varianciaX * varianciaY);
}

// Faixas calibradas pela média estadual das coortes 2015-2020 (60,32% de desistência).
function faixaDoCurso(valor) {
  if (valor >= 65) return { classe: "faixa-alta", rotulo: "Crítico" };
  if (valor >= 55) return { classe: "faixa-media", rotulo: "Atenção" };
  if (valor >= 45) return { classe: "faixa-baixa", rotulo: "Controlado" };
  return { classe: "faixa-minima", rotulo: "Saudável" };
}

function iniciais(nome) {
  const palavras = nome.split(" ").filter((palavra) => palavra.length > 2);
  const letras = palavras.length > 1 ? palavras.map((palavra) => palavra[0]).join("").slice(0, 2) : nome.slice(0, 2);
  return letras.toUpperCase();
}

