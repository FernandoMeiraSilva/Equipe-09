function indiceAtipico() {
  const { anos, grupos } = dados.redes;
  const desvios = anos.map((_, indice) => soma(grupos.map((grupo) => grupo.evasao[indice] / (soma(grupo.evasao) / anos.length) - 1)) / grupos.length);
  const maior = desvios.reduce((posicao, valor, indice) => (Math.abs(valor) > Math.abs(desvios[posicao]) ? indice : posicao), 0);
  return Math.abs(desvios[maior]) >= 0.1 ? maior : -1;
}

function montarEvasaoRedes(corpo) {
  const { anos, grupos } = dados.redes;
  const destaque = indiceAtipico();
  const ultimo = anos.length - 1;
  const maior = grupos.reduce((topo, grupo) => (grupo.evasao[ultimo] > topo.evasao[ultimo] ? grupo : topo));
  const menor = grupos.reduce((base, grupo) => (grupo.evasao[ultimo] < base.evasao[ultimo] ? grupo : base));
  const atipico = destaque >= 0 ? `O ano de ${anos[destaque]} destoa das demais séries.` : "Nenhum ano destoa de forma clara.";
  resposta(corpo, `Em ${anos[ultimo]}, ${maior.nome} tem a maior evasão anual (${pct(maior.evasao[ultimo])}) e ${menor.nome} a menor (${pct(menor.evasao[ultimo])}). ${atipico}`);
  desenharGrupos(corpo, {
    categorias: anos,
    series: grupos.map((grupo) => ({ nome: grupo.nome, valores: grupo.evasao })),
    max: 35, divisoes: 7, titulo: "Evasão anual (%)", destaque
  });
}

function montarMatriculas(corpo) {
  const { anos, grupos } = dados.redes;
  const crescimento = (grupo) => grupo.matriculas[grupo.matriculas.length - 1] / grupo.matriculas[0] - 1;
  const lider = grupos.reduce((topo, grupo) => (crescimento(grupo) > crescimento(topo) ? grupo : topo));
  resposta(corpo, `${lider.nome} cresce ${Math.round(crescimento(lider) * 100)}% entre ${anos[0]} e ${anos[anos.length - 1]} (${formatar(lider.matriculas[0])} → ${formatar(lider.matriculas[lider.matriculas.length - 1])} mil matrículas).`);
  desenharGrupos(corpo, {
    categorias: anos,
    series: grupos.map((grupo) => ({ nome: grupo.nome, valores: grupo.matriculas })),
    max: 100, divisoes: 5, titulo: "Matrículas (mil)"
  });
}

